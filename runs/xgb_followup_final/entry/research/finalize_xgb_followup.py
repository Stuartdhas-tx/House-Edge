"""Fit the single preselected follow-up finalist and prepare a stdlib entry.

Does not read validation targets, score candidates, or upload anything. The
authoritative CSVs are generated by the exact portable entry predictor.
"""
import argparse
import hashlib
import json
import platform
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
import scipy
import xgboost as xgb

from common import ROOT, Snapshots, load_split
from cv_pair_rule import agg_weights, five
from cv_xgb import CORRECTION, PROBABILITY_NAMES, fit_predict_booster, normalized_training_weights
from followup_calibration import fit_calibrator
from house_edge.registry import build_model
from xgb_features import build_features


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def dump(path, data):
    Path(path).write_text(json.dumps(data, indent=2, sort_keys=True, allow_nan=False) + "\n")


PREDICT_SOURCE = '''import argparse
import json
from pathlib import Path
from house_edge.registry import load_model
from house_edge.followup_predict import predict_followup
from house_edge.xgb_portable import PortableXGBoost
from slot_forecasting.io import load_inputs, write_submission

p = argparse.ArgumentParser()
p.add_argument('--data', required=True)
p.add_argument('--out', required=True)
p.add_argument('--split', choices=('test', 'validation'), default='test')
a = p.parse_args()
root = Path(__file__).resolve().parent
base = load_model(root / 'base_model.json')
post = json.loads((root / 'postprocess.json').read_text())
booster = None if post['kind'] == 'type_size_cal' else PortableXGBoost.load(root / 'booster.json')
queries, history = load_inputs(Path(a.data) / a.split)
write_submission(a.out, predict_followup(base, post, queries, history, booster=booster))
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cv", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    cv, out = Path(args.cv), Path(args.out)
    report = json.loads((cv / "cv.json").read_text())
    kind = report["selected_for_one_validation_comparison"]
    if kind is None or not report["screening"][kind]["eligible"]:
        raise SystemExit("No eligible frozen finalist. Keep EXP-5.")
    if out.exists():
        raise SystemExit("Choose a fresh output directory.")
    for name, expected in report["source_sha256"].items():
        if digest(ROOT / name) != expected:
            raise SystemExit(f"Benchmark source changed: {name}")
    current_inputs = {p.name: digest(p) for p in sorted((ROOT / "public/train").glob("*.csv"))}
    if current_inputs != report["input_sha256"]:
        raise SystemExit("Training inputs changed since candidate selection.")
    start = time.perf_counter()
    q, history, labels, conditions = load_split("train")
    snaps = Snapshots(q, history, labels, conditions, k_back=16)
    original = np.load(cv / "original/oof_predictions.npz", allow_pickle=False)
    for name, expected in (("query_id", snaps.qid), ("episode_id", snaps.episode),
                           ("tick", snaps.tick), ("real", snaps.real), ("outcome", snaps.y)):
        if not np.array_equal(original[name], expected):
            raise SystemExit(f"Original OOF rows do not match training data: {name}")
    raw_win, raw_size = original["exp5_raw_win"], original["exp5_raw_size"]
    raw_probabilities = five(raw_win, raw_size)
    every = np.ones(len(snaps.rows), bool)
    entry = out / "entry"
    entry.mkdir(parents=True)
    post = {"kind": kind}
    timing = {}
    t = time.perf_counter()
    if kind == "type_size_cal":
        theta, diagnostics = fit_calibrator(raw_win, raw_size, snaps.mtype, snaps.y, agg_weights(snaps, every))
        if not diagnostics["success"]:
            raise RuntimeError("Final calibration did not converge.")
        post["theta"] = theta.tolist()
        dump(out / "calibration_fit.json", diagnostics)
    else:
        if kind == "compact_xgb":
            features = np.eye(3, dtype=np.float32)[snaps.mtype]
            names = ["type_balanced", "type_jackpot", "type_steady"]
        else:
            features, names = build_features(snaps)
        x = np.column_stack([features, raw_probabilities]).astype(np.float32)
        names = list(names) + list(PROBABILITY_NAMES)
        fit_predict_booster(x, snaps.y, normalized_training_weights(snaps, every), x[:1], names,
                            parameters=CORRECTION["parameters"], rounds=CORRECTION["rounds"],
                            train_base=raw_probabilities, predict_base=raw_probabilities[:1],
                            model_path=entry / "booster.json")
        if kind == "half_full":
            # Same four-parameter objective as CV, using original OOF win AND size.
            from scipy.optimize import minimize
            from joint_numpy import calibrated_win
            weights = agg_weights(snaps, every)
            def objective(theta):
                p = five(calibrated_win(raw_win, theta, snaps.mtype), raw_size)
                return float(weights @ ((p - snaps.Y) ** 2).sum(axis=1))
            fit = minimize(objective, np.array([1., 0., 0., 0.]), method="Nelder-Mead",
                           options={"xatol": 1e-4, "fatol": 1e-7, "maxiter": 2000})
            if not fit.success:
                raise RuntimeError("Final baseline calibration did not converge.")
            post["baseline_theta"] = fit.x.tolist()
    timing["postprocessor_fit"] = time.perf_counter() - t
    config = dict(report["exp5_config"])
    config.update(model="size_rule", calibration_slope=1.0,
                  calibration_intercepts={"balanced": 0.0, "jackpot": 0.0, "steady": 0.0})
    t = time.perf_counter()
    base = build_model(config).fit(q, history, labels)
    base.save(entry / "base_model.json")
    timing["base_fit"] = time.perf_counter() - t
    dump(entry / "postprocess.json", post)
    dump(entry / "reproduce.json", {"image": "python", "command": [
        "python", "predict.py", "--data", "/data", "--out", "/output/submission.csv"]})
    (entry / "predict.py").write_text(PREDICT_SOURCE)
    # Prediction modules need no third-party dependencies. Training sources are
    # included for provenance/local retraining, but the reproduction loads checkpoints.
    for directory in ("house_edge", "slot_forecasting", "research"):
        target = entry / directory
        target.mkdir()
        for path in sorted((ROOT / directory).glob("*.py")):
            shutil.copyfile(path, target / path.name)
    (entry / "configs").mkdir()
    for path in (ROOT / "configs").glob("*.json"):
        shutil.copyfile(path, entry / "configs" / path.name)
    for name in ("XGB_BENCHMARK_PLAN.md", "XGB_FOLLOWUP_PLAN.md"):
        shutil.copyfile(ROOT / name, entry / name)
    versions = {"python": platform.python_version(), "numpy": np.__version__,
                "scipy": scipy.__version__, "xgboost": xgb.__version__}
    (entry / "requirements-training.txt").write_text("\n".join(
        f"{name}=={versions[name]}" for name in ("numpy", "scipy", "xgboost")) + "\n")
    freeze = {"selected": kind, "selection_report_sha256": digest(cv / "cv.json"),
              "original_oof_sha256": digest(cv / "original/oof_predictions.npz"),
              "train_sha256": current_inputs, "training_versions": versions,
              "postprocess": post, "base_config": config,
              "xgb_settings": None if kind == "type_size_cal" else CORRECTION,
              "prediction_source_sha256": {str(p.relative_to(entry)): digest(p)
                                           for directory in (entry / "house_edge", entry / "slot_forecasting")
                                           for p in directory.glob("*.py")},
              "checkpoint_sha256": {p.name: digest(p) for p in entry.glob("*.json")},
              "validation_targets_read": False, "uploaded": False}
    dump(out / "freeze.json", freeze)
    dump(entry / "training-run.json", freeze)
    (entry / "README.md").write_text(f'''# House Edge Main — {kind}

Team: use the same registered team selected on the submission Form. Round: Main.
Inference: Python 3.11+ standard library only; tested interpreter versions are recorded alongside the submitted artifacts after verification. No downloads, installation, GPU, or training are needed for reproduction.

Run `python predict.py --data /data --out /output/submission.csv` from this folder. The script reads only test queries/history and the supplied checkpoints. The forecast CSV is submitted separately.

EXP-5 global parameters were fitted on organizer Main TRAIN. The fixed postprocessor was trained on original-partition episode-OOF EXP-5 predictions and historical features. Three fixed TRAIN partitions were used as sensitivity checks to select this candidate. No validation targets were used to train coefficients. See training-run.json for exact settings, seeds, hashes, and training dependency versions; the experiment plans describe selection and its limitations. Training sources and requirements-training.txt are included for local research with the organizer public/ directory, not needed by the offline reproduction command.

XGBoost trees, if present, are evaluated with the included portable Python runtime. The authoritative CSV uses that runtime; small differences from native XGBoost's softmax are expected. Validation and test prediction use the same saved files and preprocessing.
''')
    for split, filename in (("validation", "validation_predictions.csv"), ("test", "submission.csv")):
        t = time.perf_counter()
        subprocess.run([sys.executable, "-S", str(entry.resolve() / "predict.py"),
                        "--data", str(ROOT / "public"), "--split", split,
                        "--out", str((out / filename).resolve())], check=True, cwd=entry)
        timing[f"predict_{split}"] = time.perf_counter() - t
    subprocess.run([sys.executable, str(ROOT / "build_entry.py"), "--source", str(entry.resolve()),
                    "--out", str((out / "entry.zip").resolve())], check=True)
    timing["total"] = time.perf_counter() - start
    dump(out / "run.json", {**freeze, "seconds": timing,
                            "artifact_sha256": {name: digest(out / name) for name in (
                                "submission.csv", "validation_predictions.csv", "entry.zip")},
                            "reproduction_verified": False, "validation_scored": False})
    print(json.dumps({"selected": kind, "seconds": timing, "out": str(out),
                      "validation_scored": False, "reproduction_verified": False}, indent=2))


if __name__ == "__main__":
    main()
